const LanguageContext = createContext({ language: 'en' as Language, toggleLanguage: () => {}, t: (text: string) => english[text] ?? text });

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>('en');
  const t = (text: string) => language === 'en' ? english[text] ?? text : text;
  return <LanguageContext.Provider value={{ language, toggleLanguage: () => setLanguage(current => current === 'en' ? 'es' : 'en'), t }}>{children}</LanguageContext.Provider>;
}
export const useLanguage = () => useContext(LanguageContext);
